const { test, after } = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs'), os = require('node:os'), path = require('node:path');
const { spawnSync } = require('node:child_process');
const directory = fs.mkdtempSync(path.join(os.tmpdir(), 'byd-content-sync-'));
process.env.DB_PATH = path.join(directory, 'test.sqlite');
const store = require('../server/database');
const { QR_IMAGE, validate, mergedNews, plan, synchronize } = require('../server/sync-wordpress-content');
const imported = require('../server/data/news.json');
after(() => { store.db.close(); fs.rmSync(directory, { recursive: true, force: true }); });
test('import merges missing posts, preserves edits, and only unpublishes the reviewed QR slide', () => {
  validate(imported);
  const staff = { id:'staff', title:'Staff event', category:'Event', published:true };
  const edited = { ...imported[0], title:'Edited by staff', published:false };
  const renamed = { ...imported[1], id:'local-import-id', published:false };
  store.writeJson('news.json', [staff, edited, renamed]);
  store.save('hero_slides', { id:'old-klang-road', mediaUrl:QR_IMAGE, published:true, headline:'Old Klang Road' });
  const otherSlides = store.list('hero_slides').filter(slide => slide.id !== 'old-klang-road');
  const vehicles = store.list('vehicles');
  store.writeJson('submissions/enquiries.json', [{ id:'private-fixture' }]);
  const reviewed = plan(store, imported);
  assert.equal(reviewed.addedPosts, 61); assert.equal(reviewed.totalPosts, 64);
  store.save('hero_slides', { ...otherSlides[0], headline:'Changed after planning' });
  assert.throws(() => synchronize(store, imported, reviewed.currentFingerprint), /changed since review/);
  store.save('hero_slides', otherSlides[0]);
  synchronize(store, imported, plan(store, imported).currentFingerprint);
  const result = store.readJson('news.json');
  assert.deepEqual(result.slice(0,3), [staff, edited, renamed]);
  assert.equal(result.length, 64);
  assert.equal(store.list('hero_slides').find(slide => slide.id === 'old-klang-road').published, false);
  assert.deepEqual(store.list('hero_slides').filter(slide => slide.id !== 'old-klang-road'), otherSlides);
  assert.deepEqual(store.list('vehicles'), vehicles);
  assert.deepEqual(store.readJson('submissions/enquiries.json'), [{ id:'private-fixture' }]);
  assert.equal(plan(store, imported).addedPosts, 0);
  assert.equal(plan(store, imported).unpublishQr, false);
  assert.throws(() => mergedNews([{ id:imported[0].id, title:'Unrelated staff post' }], imported), /conflicts/);
  store.save('hero_slides', { id:'old-klang-road', mediaUrl:'/uploads/new-image.png', published:true });
  assert.throws(() => plan(store, imported), /QR slide has changed/);
  store.save('hero_slides', { id:'old-klang-road', mediaUrl:QR_IMAGE, published:true });
});
test('CLI defaults to preview and backs up the original database privately before applying', () => {
  const run = args => spawnSync(process.execPath, ['server/sync-wordpress-content.js', ...args], { cwd:path.join(__dirname,'..'), env:process.env, encoding:'utf8' });
  const reviewed = plan(store, imported);
  const preview = run([]); assert.equal(preview.status, 0, preview.stderr);
  assert.equal(JSON.parse(preview.stdout).applied, false);
  assert.equal(plan(store, imported).currentFingerprint, reviewed.currentFingerprint);
  const applied = run(['--apply', '--expected', reviewed.currentFingerprint]);
  assert.equal(applied.status, 0, applied.stderr);
  const output = JSON.parse(applied.stdout);
  assert.equal(fs.statSync(output.backupPath).mode & 0o777, 0o600);
  const { DatabaseSync } = require('node:sqlite');
  const backup = new DatabaseSync(output.backupPath, { readOnly:true });
  assert.equal(backup.prepare('PRAGMA integrity_check').get().integrity_check, 'ok');
  assert.equal(JSON.parse(backup.prepare('SELECT data FROM hero_slides WHERE id=?').get('old-klang-road').data).published, true);
  backup.close();
});
