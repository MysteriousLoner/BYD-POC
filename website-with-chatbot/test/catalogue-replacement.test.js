const { test, after } = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { spawnSync } = require('node:child_process');
const temporary = fs.mkdtempSync(path.join(os.tmpdir(), 'byd-catalogue-'));
process.env.DB_PATH = path.join(temporary, 'test.sqlite');
const store = require('../server/database');
const { fingerprint, validate, plan, replace } = require('../server/replace-catalogue');
const catalogue = require('../server/data/models.json');
after(() => { store.db.close(); fs.rmSync(temporary, { recursive: true, force: true }); });

test('catalogue replacement preserves current offers and submissions, archives retired offers and rejects stale plans', () => {
  validate(catalogue);
  const { comparison } = require('../js/catalogue-data');
  const brakeRows = comparison(catalogue.filter(model => ['byd-sea-lion', 'm6'].includes(model.id))).filter(row => /^(front|rear)(-disc)?-brake$/.test(row.key));
  assert.equal(brakeRows.length, 2);
  assert(brakeRows.every(row => row.values.every(value => value !== 'Not specified')));
  store.save('vehicles', { id: 'obsolete', name: 'Obsolete vehicle', published: true });
  store.save('promotions', { id: 'retained-offer', model: 'seal', published: false, terms: 'Preserve this offer' });
  store.writeJson('submissions/enquiries.json', [{ id: 'private-fixture', model: 'Historic vehicle name' }]);
  const offers = store.list('promotions');
  const submissions = store.readJson('submissions/enquiries.json');
  const before = fingerprint(store.list('vehicles'));
  const reviewed = plan(store, catalogue).currentFingerprint;
  assert.equal(fingerprint(store.list('vehicles')), before, 'planning must not replace data');
  store.save('vehicles', { ...store.list('vehicles')[0], description: 'Changed after review' });
  assert.throws(() => replace(store, catalogue, reviewed), /changed since review/);
  assert(store.list('vehicles').some(model => model.id === 'obsolete'));
  store.save('promotions', { id: 'blocked-offer', model: 'obsolete', published: false });
  const approved = plan(store, catalogue).currentFingerprint;
  assert.equal(plan(store, catalogue).archivedPromotions, 1);
  store.save('promotions', { ...offers[0], terms: 'Changed offer after review' });
  assert.throws(() => replace(store, catalogue, approved), /changed since review/);
  store.save('promotions', offers[0]);
  const result = replace(store, catalogue, plan(store, catalogue).currentFingerprint);
  assert.equal(result.applied, true);
  assert.deepEqual(new Set(store.list('vehicles').map(model => model.id)), new Set(catalogue.map(model => model.id)));
  assert.deepEqual(store.list('promotions'), offers);
  const archive = store.readJson('catalogue-archives/sime-motors-20261117-' + approved + '.json');
  assert.equal(archive.models[0].id, 'obsolete');
  assert.equal(archive.promotions[0].id, 'blocked-offer');
  assert.deepEqual(store.readJson('submissions/enquiries.json'), submissions);
  assert.equal(store.db.prepare('PRAGMA foreign_key_check').all().length, 0);
  assert.equal(store.db.prepare('SELECT count(*) AS n FROM vehicle_images').get().n, catalogue.reduce((sum, model) => sum + model.images.length, 0));
});

test('explicit CLI previews by default and creates a private consistent backup when applying', () => {
  const run = args => spawnSync(process.execPath, ['server/replace-catalogue.js', ...args], { cwd: path.join(__dirname, '..'), env: process.env, encoding: 'utf8' });
  const before = plan(store, catalogue).currentFingerprint;
  const preview = run([]);
  assert.equal(preview.status, 0, preview.stderr);
  assert.equal(JSON.parse(preview.stdout).applied, false);
  assert.equal(plan(store, catalogue).currentFingerprint, before);
  const applied = run(['--apply', '--expected', before]);
  assert.equal(applied.status, 0, applied.stderr);
  const output = JSON.parse(applied.stdout);
  assert.equal(output.applied, true);
  assert(fs.existsSync(output.backupPath));
  assert.equal(fs.statSync(output.backupPath).mode & 0o777, 0o600);
  const { DatabaseSync } = require('node:sqlite');
  const backup = new DatabaseSync(output.backupPath, { readOnly: true });
  assert.equal(backup.prepare('PRAGMA integrity_check').get().integrity_check, 'ok');
  assert.equal(backup.prepare('SELECT count(*) AS n FROM vehicles').get().n, 7);
  backup.close();
});
